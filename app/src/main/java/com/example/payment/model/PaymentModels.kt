package com.example.payment.model

/**
 * Standard Payment Status values representing the immediate transaction lifecycle state.
 */
enum class PaymentStatus(val displayName: String) {
    PENDING("Pending"),
    SUCCESSFUL("Successful"),
    FAILED("Failed"),
    CANCELLED("Cancelled"),
    REFUNDED("Refunded");

    companion object {
        fun fromString(value: String): PaymentStatus {
            return entries.find {
                it.name.equals(value, ignoreCase = true) || it.displayName.equals(value, ignoreCase = true)
            } ?: PENDING
        }
    }
}

/**
 * Bank Settlement Status kept strictly distinct from gateway transaction PaymentStatus.
 * Tracks actual merchant bank deposit lifecycle.
 */
enum class BankSettlementStatus(val displayName: String) {
    UNSETTLED("Unsettled"),
    PENDING_SETTLEMENT("Pending Settlement"),
    SETTLED("Settled to Bank"),
    SETTLEMENT_FAILED("Settlement Failed"),
    REVERSED("Reversed");

    companion object {
        fun fromString(value: String): BankSettlementStatus {
            return entries.find {
                it.name.equals(value, ignoreCase = true) || it.displayName.equals(value, ignoreCase = true)
            } ?: UNSETTLED
        }
    }
}

/**
 * Provider-independent payment modes supported in SK Mobile store.
 */
enum class PaymentMethodType(val displayName: String) {
    UPI("UPI"),
    CARD("Debit / Credit Card"),
    NET_BANKING("Net Banking"),
    CASH_ON_DELIVERY("Cash on Delivery");

    companion object {
        fun fromString(value: String): PaymentMethodType {
            return when {
                value.contains("UPI", ignoreCase = true) -> UPI
                value.contains("Card", ignoreCase = true) -> CARD
                value.contains("Net", ignoreCase = true) || value.contains("Bank", ignoreCase = true) -> NET_BANKING
                value.contains("Cash", ignoreCase = true) || value.contains("COD", ignoreCase = true) -> CASH_ON_DELIVERY
                else -> CASH_ON_DELIVERY
            }
        }
    }
}

/**
 * Secure, provider-independent order initiation request dispatched to trusted backend.
 * Uses idempotencyKey to prevent duplicate order generation.
 */
data class PaymentOrderRequest(
    val orderId: String,
    val amountPaise: Long, // Amount in paise for Indian payment gateways (1 INR = 100 paise)
    val currency: String = "INR",
    val customerUid: String,
    val customerName: String,
    val customerEmail: String,
    val customerPhone: String,
    val paymentMethodType: PaymentMethodType,
    val idempotencyKey: String, // Unique idempotency key per checkout attempt
    val notes: Map<String, String> = emptyMap()
)

/**
 * Secure gateway order session generated by trusted backend.
 * Contains only client-safe identifiers (orderId, keyId, etc.), never secret keys.
 */
data class PaymentGatewayOrderSession(
    val gatewayOrderId: String,
    val provider: String, // e.g., "RAZORPAY", "CASHFREE", "PHONEPE", "OFFLINE"
    val amountPaise: Long,
    val currency: String = "INR",
    val clientKeyId: String, // Publishable client/app key only (never secret API key)
    val idempotencyKey: String,
    val status: PaymentStatus = PaymentStatus.PENDING
)

/**
 * Client submission of gateway signature payload for server-side verification.
 * The mobile client sends this to the trusted backend; it does NOT directly mark orders paid in Firestore.
 */
data class PaymentVerificationRequest(
    val orderId: String,
    val gatewayOrderId: String,
    val gatewayPaymentId: String,
    val gatewaySignature: String,
    val idempotencyKey: String
)

/**
 * Trusted verification response from server-side signature check.
 */
data class PaymentVerificationResult(
    val isVerified: Boolean,
    val orderId: String,
    val paymentStatus: PaymentStatus,
    val bankSettlementStatus: BankSettlementStatus,
    val message: String,
    val transactionRef: String? = null
)
